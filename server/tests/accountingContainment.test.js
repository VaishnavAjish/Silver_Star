/**
 * ACCOUNTING PHASE 0 — containment regression suite.
 *
 * Two layers:
 *   1. PURE — the shared decision rule (services/accountingContainment.js).
 *   2. ROUTE — the real Express handlers driven against a FAKE database client
 *      that records every SQL string. This is what proves the critical claims:
 *      a blocked operation issues ZERO DELETE SQL, changes ZERO account
 *      balances and removes ZERO payment allocations.
 *
 * No PostgreSQL required: db/pool is stubbed through require.cache before the
 * routers are loaded. Run with:
 *     node --test tests/accountingContainment.test.js
 * (server/package.json's "test" script is `node test_db.js` and needs a live DB —
 *  do not use it for this suite.)
 */

'use strict';

const { test, after } = require('node:test');
const assert          = require('node:assert');
const Module          = require('node:module');

after(async () => {
  try {
    const poolPath = require.resolve('../db/pool');
    if (require.cache[poolPath]) {
      const p = require(poolPath);
      if (typeof p.shutdown === 'function') await p.shutdown();
      else if (p.primaryPool && typeof p.primaryPool.end === 'function') await p.primaryPool.end();
    }
  } catch (e) {}
});

