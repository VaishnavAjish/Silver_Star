// ═════════════════════════ 2. ROUTE-LEVEL ════════════════════════════════════
// Drive the REAL handlers with a fake pool. Asserts the operation is refused
// with 409 AND that not one destructive statement reached the database.

/** Records every SQL string; answers queries from a scripted responder. */
function makeFakeClient(responder) {
  const sql = [];
  return {
    sql,
    released: false,
    async query(text, params) {
      sql.push(String(text));
      return responder(String(text), params) || { rows: [], rowCount: 0 };
    },
    release() { this.released = true; },
  };
}

function makeRes() {
  return {
    statusCode: null,
    body: null,
    status(c) { this.statusCode = c; return this; },
    json(b) { this.body = b; return this; },
  };
}

/** Install a stubbed db/pool into require.cache, then load a router fresh. */
function loadRouterWithFakePool(routerRelPath, client) {
  const poolPath   = require.resolve('../db/pool');
  const routerPath = require.resolve(routerRelPath);

  const savedPool   = require.cache[poolPath];
  const savedRouter = require.cache[routerPath];

  const fakePool = {
    query: async () => ({ rows: [], rowCount: 0 }),
    primaryPool: { connect: async () => client },
    connect: async () => client,
    transaction: async (fn) => fn(client),
  };
  const stub = new Module(poolPath, null);
  stub.filename = poolPath;
  stub.loaded   = true;
  stub.exports  = fakePool;
  require.cache[poolPath] = stub;

  delete require.cache[routerPath];
  const router = require(routerRelPath);

  // restore so other suites are unaffected
  delete require.cache[routerPath];
  if (savedPool) require.cache[poolPath] = savedPool; else delete require.cache[poolPath];
  if (savedRouter) require.cache[routerPath] = savedRouter;

  return router;
}

/** Pull a layer's terminal handler out of an Express router. */
function findHandler(router, method, routePath) {
  const layer = router.stack.find(
    l => l.route && l.route.path === routePath && l.route.methods[method]
  );
  assert.ok(layer, `route ${method.toUpperCase()} ${routePath} not found`);
  const stack = layer.route.stack;
  return stack[stack.length - 1].handle;
}

/** No statement may destroy accounting data or move a balance. */
function assertNoDestructiveSql(sql) {
  const destructive = sql.filter(s =>
    /\bDELETE\s+FROM\b/i.test(s) ||
    /\bUPDATE\s+accounts\b/i.test(s) ||
    /\bUPDATE\s+purchase_notes\b/i.test(s) ||
    /\bUPDATE\s+journal_entries\b/i.test(s) ||
    /\bUPDATE\s+payments\b/i.test(s)
  );
  assert.deepEqual(destructive, [], `blocked path issued destructive SQL:\n${destructive.join('\n')}`);
  assert.ok(sql.some(s => /^\s*ROLLBACK/i.test(s)), 'blocked path must ROLLBACK');
  assert.ok(!sql.some(s => /^\s*COMMIT/i.test(s)), 'blocked path must never COMMIT');
}

test('route: DELETE je-allocation with POSTED parent -> 409, zero DELETE SQL', async () => {
  const client = makeFakeClient((text) => {
    if (/FROM je_allocations WHERE id/i.test(text)) {
      return { rows: [{ id: 5, je_id: postedManualJe.id, target_type: 'bill', target_id: 3 }] };
    }
    if (/FROM journal_entries WHERE id/i.test(text)) return { rows: [postedManualJe] };
    if (/COUNT\(\*\)::int AS payment_refs/i.test(text)) return { rows: [{ payment_refs: 0 }] };
    return { rows: [] };
  });

  const router  = loadRouterWithFakePool('../routes/jeAllocations', client);
  const handler = findHandler(router, 'delete', '/:id');
  const res     = makeRes();

  await handler({ params: { id: '5' }, user: { id: 1, role: 'super_admin' }, body: {} }, res);

  assert.equal(res.statusCode, CONFLICT);
  assert.equal(res.body.code, ACCOUNTING_TRANSACTION_POSTED);
  assertNoDestructiveSql(client.sql);
  assert.ok(client.sql.some(s => /FROM journal_entries WHERE id = \$1 FOR UPDATE/i.test(s)),
    'parent JE must be locked with FOR UPDATE');
});

